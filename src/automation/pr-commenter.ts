import { Octokit } from '@octokit/rest'
import { buildContext, formatContext } from '../query/context-builder.js'
import { query } from '../query/engine.js'
import type { RepoConfig } from '../config/schema.js'

export async function commentOnPR(
  repo: RepoConfig,
  prNumber: number,
  commitSha: string,
): Promise<void> {
  const octokit = new Octokit({ auth: process.env.GITHUB_TOKEN })
  const [owner, repoName] = repo.remote.replace('https://github.com/', '').split('/')

  const ctx = buildContext(repo.name)
  const contextStr = formatContext(ctx)

  const system = `You are a codebase analyst. Given recent changes and hot zones,
write a concise PR review briefing (3-5 bullets). Flag risk areas.
Format: markdown. Start with overall risk level: LOW/MEDIUM/HIGH.`

  const userPrompt = `${contextStr}\n\nCommit: ${commitSha}\n
Write PR briefing for reviewers.`

  const briefing = await query(system, userPrompt, { maxTokens: 500 })

  const body = `## Brain Analysis\n\n${briefing}\n\n---\n*Generated by [Living Codebase Brain](https://github.com/Aryan1092raj/Daemon) · ${new Date().toISOString().slice(0, 10)}*`

  await octokit.issues.createComment({
    owner, repo: repoName,
    issue_number: prNumber,
    body,
  })

  console.info(`[brain/automation] posted PR #${prNumber} comment`)
}
