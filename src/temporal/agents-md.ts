import fs from 'node:fs/promises'
import path from 'node:path'
import { getDb } from '../memory/db.js'
import { getCurrentHotZones } from './hotzone.js'
import { getKuzuClient } from '../graph/client.js'

/**
 * Generates an AGENTS.md file in the root of the repository path
 * to provide temporal codebase context to AI coding assistants.
 */
export async function generateAgentsMd(
  repoName: string,
  repoPath: string
): Promise<void> {
  const db = getDb()
  const kuzu = getKuzuClient()

  // 1. Fetch counts
  const symbolCount = (db.prepare(`SELECT COUNT(DISTINCT symbol_fqn) as c FROM change_events WHERE repo = ?`).get(repoName) as { c: number })?.c ?? 0
  const fileCount = (db.prepare(`SELECT COUNT(DISTINCT file_path) as c FROM change_events WHERE repo = ?`).get(repoName) as { c: number })?.c ?? 0

  // 2. Fetch hot zones
  const hotzones = getCurrentHotZones(repoName).slice(0, 10)

  // 3. Fetch decaying/cold files from Kuzu
  const coldFiles = await kuzu.query<{
    path: string
    decayScore: number
    lastTouched: string
  }>(`
    MATCH (f:File {repo: $repo})
    RETURN f.path AS path, f.decay_score AS decayScore, f.last_touched AS lastTouched
    ORDER BY f.decay_score ASC
    LIMIT 10
  `, { repo: repoName }).catch(() => [])

  // 4. Fetch recent episodes
  const episodes = db.prepare(`
    SELECT date, summary
    FROM tier2_episodes
    WHERE repo = ?
    ORDER BY date DESC
    LIMIT 5
  `).all(repoName) as Array<{ date: string; summary: string }>

  // Build markdown content
  const mdLines: string[] = [
    `# Repository Intelligence Summary`,
    ``,
    `*This file is dynamically generated by the Brain daemon to provide AI coding assistants (like Antigravity, Cursor, Claude) with high-fidelity temporal context about the current state, hot spots, and recent changes in this repository.*`,
    ``,
    `## 📊 Codebase Health & Statistics`,
    `- **Files Tracked**: ${fileCount}`,
    `- **Symbols Analyzed**: ${symbolCount}`,
    `- **Active Hot Zones**: ${hotzones.length}`,
    `- **Last Updated**: ${new Date().toUTCString()}`,
    ``,
  ]

  if (hotzones.length > 0) {
    mdLines.push(
      `## 🔥 Anomalous Hot Zones (High Change Velocity)`,
      `These symbols/files have been modified abnormally often recently. Focus changes here carefully.`,
      `| Symbol | File | Velocity | Z-Score |`,
      `| :--- | :--- | :--- | :--- |`
    )
    for (const hz of hotzones) {
      const symName = hz.symbolFqn.split(':').pop() ?? hz.symbolFqn
      mdLines.push(`| \`${symName}\` | \`${hz.filePath}\` | ${hz.velocity.toFixed(1)}/day | **${hz.zScore.toFixed(2)}** |`)
    }
    mdLines.push(``)
  }

  if (coldFiles.length > 0) {
    mdLines.push(
      `## ❄️ Decaying / Cold Zones (Forgotten Code)`,
      `These files have low freshness scores, meaning they have not been touched for a long time. Watch out for architectural rot or outdated assumptions.`,
      `| File | Freshness | Last Touched |`,
      `| :--- | :--- | :--- |`
    )
    for (const file of coldFiles) {
      const freshness = (file.decayScore * 100).toFixed(0)
      const lastTouchedDate = file.lastTouched ? new Date(file.lastTouched).toLocaleDateString() : 'Unknown'
      mdLines.push(`| \`${file.path}\` | ${freshness}% | ${lastTouchedDate} |`)
    }
    mdLines.push(``)
  }

  if (episodes.length > 0) {
    mdLines.push(
      `## 📝 Recent Development Episodes`,
      `Recent summaries of work completed in this repository:`,
      ``
    )
    for (const ep of episodes) {
      mdLines.push(`### 🗓️ ${ep.date}`)
      mdLines.push(`${ep.summary}`)
      mdLines.push(``)
    }
  } else {
    mdLines.push(
      `## 📝 Recent Development Episodes`,
      `No episodic memory logs recorded yet. Run scan or push changes to update.`,
      ``
    )
  }

  const markdown = mdLines.join('\n')
  const agentsMdPath = path.join(repoPath, 'AGENTS.md')
  
  await fs.writeFile(agentsMdPath, markdown, 'utf-8')
  console.info(`[brain] updated temporal context file: ${agentsMdPath}`)
}
