import { getKuzuClient } from '../graph/client.js'
import fs from 'node:fs/promises'
import path from 'node:path'

export interface AgentsContext {
  repoName: string
  repoPath: string
  language: string
  totalFiles: number
  totalSymbols: number
  exportedSymbols: ExportedSymbol[]
  modules: ModuleSummary[]
  hotFiles: HotFile[]
  lastCommitSha: string
  generatedAt: string
}

interface ExportedSymbol { fqn: string; kind: string; file: string }
interface ModuleSummary   { name: string; symbolCount: number }
interface HotFile         { path: string; velocity: number }

export async function generateAgentsMd(
  repoName: string,
  repoPath: string,
  commitSha: string,
  hotFiles: HotFile[] = [],
): Promise<void> {
  const db = getKuzuClient()

  const filesResult = await db.query<{ count: number }>(
    `MATCH (f:File {repo: $r}) RETURN count(f) AS count`, { r: repoName }
  )
  const symbolsResult = await db.query<{ count: number }>(
    `MATCH (s:Symbol {repo: $r}) RETURN count(s) AS count`, { r: repoName }
  )
  const exportedResult = await db.query<ExportedSymbol>(
    `MATCH (s:Symbol {repo: $r, is_exported: true})
     RETURN s.fqn AS fqn, s.kind AS kind, s.file AS file
     ORDER BY s.file LIMIT 200`, { r: repoName }
  )
  const langResult = await db.query<{ language: string; count: number }>(
    `MATCH (f:File {repo: $r})
     RETURN f.language AS language, count(f) AS count
     ORDER BY count DESC LIMIT 1`, { r: repoName }
  )

  const ctx: AgentsContext = {
    repoName,
    repoPath,
    language: langResult[0]?.language ?? 'unknown',
    totalFiles: filesResult[0]?.count ?? 0,
    totalSymbols: symbolsResult[0]?.count ?? 0,
    exportedSymbols: exportedResult,
    modules: [],
    hotFiles,
    lastCommitSha: commitSha,
    generatedAt: new Date().toISOString(),
  }

  const content = renderAgentsMd(ctx)
  const outPath = path.join(repoPath, 'AGENTS.md')
  await fs.writeFile(outPath, content, 'utf-8')
}

function renderAgentsMd(ctx: AgentsContext): string {
  const exportedByFile = ctx.exportedSymbols.reduce<Record<string, ExportedSymbol[]>>(
    (acc, s) => { (acc[s.file] ??= []).push(s); return acc }, {}
  )

  return `# AGENTS.md
> Auto-generated by brain daemon. Do not edit manually.
> Regenerated on every commit. Last: \`${ctx.lastCommitSha.slice(0, 7)}\` at ${ctx.generatedAt}

## Repository overview

| Property | Value |
|---|---|
| Name | ${ctx.repoName} |
| Primary language | ${ctx.language} |
| Total source files | ${ctx.totalFiles} |
| Total tracked symbols | ${ctx.totalSymbols} |

## Public API surface

These symbols are exported and should be treated as stable contracts.
Changing their signatures may break callers.

${Object.entries(exportedByFile).map(([file, syms]) => `
### \`${file}\`
${syms.map(s => `- \`${s.kind}\` **${s.fqn.split(':').pop()}**`).join('\n')}
`).join('')}

${ctx.hotFiles.length > 0 ? `
## Hot zones (high change velocity)

These files are changing rapidly. Extra caution advised.

${ctx.hotFiles.map(f => `- \`${f.path}\` — velocity score ${f.velocity.toFixed(2)}`).join('\n')}
` : ''}

## Instructions for AI agents

- Before editing any exported symbol, check its callers via the call graph.
- Prefer modifying implementation details over public interfaces.
- When adding new exports, add them to the appropriate module section.
- Do not remove exported symbols without checking all import edges.
- Hot zone files have high incident correlation — test thoroughly before committing.
`
}